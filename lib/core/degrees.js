// درجه‌ی نتیجه بر اساس «فاصله» = مجموع تاس منهای عدد لازم (یا تاس حریف در تقابل)
// min = کمترین فاصله‌ای که این درجه رو می‌گیره (ترتیب از بدترین به بهترین)
export const DEGREES = [
  {
    key: "critFail",
    min: -Infinity,
    label: "شکست سنگین",
    hint: "کار کاملاً شکست می‌خورد و یک پیامد جدی و ملموس پیش میاد.",
  },
  {
    key: "fail",
    min: -4,
    label: "شکست جزئی",
    hint: "کار انجام نمی‌شه ولی خیلی نزدیک بوده؛ فقط یک پیامد کوچک و کم‌اثر پیش میاد.",
  },
  {
    key: "edge",
    min: 0,
    label: "موفقیت لب‌مرزی",
    hint: "دقیقاً همون کاری که بازیکن خواست انجام میشه، بدون هیچ مزیت یا چیز اضافه.",
  },
  {
    key: "success",
    min: 1,
    label: "موفقیت",
    hint: "کار همون‌طور که بازیکن خواست انجام میشه.",
  },
  {
    key: "great",
    min: 5,
    label: "موفقیت درخشان",
    hint: "کار بهتر از خواسته‌ی بازیکن انجام میشه؛ یک مزیت، سرنخ یا جزئیات اضافه به دست میاد و ادامه‌ی داستان هم برای اون بازیکن بهتر از حالت معمول میشه.",
  },
];

export function degreeFor(margin) {
  let found = DEGREES[0];
  for (const d of DEGREES) {
    if (margin >= d.min) found = d;
  }
  return found;
}
